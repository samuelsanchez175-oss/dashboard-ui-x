#!/usr/bin/env node
/**
 * Periodic cross-environment check-off → vault sync (the "local cron" half).
 *
 * On localhost the dashboard writes the vault note directly (BFF /api/local/projects/checkoff).
 * This script is for check-offs made on Vercel: it pulls the shared check-off map from a cloud
 * store you control and rewrites the vault note `📊 dashboard-ui/Project Tasks.md`.
 *
 * Run by launchd every ~15 min (see scripts/PROJECT-SYNC.md). No-ops cleanly until a store is set.
 *   CHECKOFF_STORE_URL=https://... [CHECKOFF_STORE_TOKEN=...] VAULT_DIR="/path" node scripts/sync-checkoffs.mjs
 *
 * The store endpoint must return JSON {"<taskId>": true|false}; taskId = "<project.id>-<taskIndex>".
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const VAULT = process.env.VAULT_DIR || '/Users/samuel/dev/OB CLAUDE vault'
const STORE_URL = process.env.CHECKOFF_STORE_URL
const STORE_TOKEN = process.env.CHECKOFF_STORE_TOKEN
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const PROJECTS = join(repoRoot, 'public', 'data', 'projects.json')
const NOTE = join(VAULT, '📊 dashboard-ui', 'Project Tasks.md')

if (!STORE_URL) {
  console.log('CHECKOFF_STORE_URL not set — nothing to pull from the cloud (localhost writes the vault directly). Exiting.')
  process.exit(0)
}

async function loadOverrides() {
  const headers = STORE_TOKEN ? { apikey: STORE_TOKEN, authorization: `Bearer ${STORE_TOKEN}` } : undefined
  const res = await fetch(STORE_URL, headers ? { headers } : undefined)
  if (!res.ok) throw new Error(`store ${res.status}: ${(await res.text()).slice(0, 200)}`)
  const data = await res.json()
  if (Array.isArray(data)) {            // Supabase REST rows: [{task_id, done}]
    const map = {}
    for (const row of data) if (row && row.task_id != null) map[row.task_id] = !!row.done
    return map
  }
  // Or a flat {taskId: bool} map / {overrides: {...}}.
  return data && typeof data === 'object' ? (data.overrides ?? data) : {}
}

function render(projects, overrides) {
  const now = new Date().toISOString()
  const lines = [
    '---', 'type: dashboard-tasks', 'source: ui-dashboard-x',
    `updated: ${now.slice(0, 10)}`, '---', '',
    '# 📊 Project Tasks (synced from the dashboard)', '',
    '> Auto-generated by the Projects dashboard — edits here are overwritten on each sync.',
    `> Last synced: ${now} (cloud)`, '',
  ]
  for (const p of projects) {
    const tasks = (p.tasks || []).map((t, i) => ({ ...t, done: overrides[`${p.id}-${i}`] ?? t.done }))
    const done = tasks.filter(t => t.done).length
    lines.push(`## ${p.emoji ?? ''} ${p.name} — ${done}/${tasks.length}`, '')
    for (const t of tasks) {
      const who = t.owner === 'human' ? '🙋' : '🤖'
      lines.push(`- [${t.done ? 'x' : ' '}] ${who} ${String(t.title ?? '').replace(/\n/g, ' ')}`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

try {
  const { projects } = JSON.parse(readFileSync(PROJECTS, 'utf8'))
  const overrides = await loadOverrides()
  mkdirSync(dirname(NOTE), { recursive: true })
  writeFileSync(NOTE, render(projects, overrides))
  console.log(`synced ${Object.keys(overrides).length} check-offs → ${NOTE}`)
} catch (e) {
  console.error('sync failed:', e.message)
  process.exit(1)
}
