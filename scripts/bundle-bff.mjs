/**
 * Pre-bundle the dashboard BFF + agent-farm BFF into a single ESM file so the
 * Vercel serverless function (`api/[...path].ts`) can import it without
 * Vercel's bundler having to resolve TypeScript modules across the repo.
 *
 * Run as a prebuild step: see `npm run bundle:bff`.
 *
 * Output: `api/_bff-bundle.mjs` — gitignored, regenerated on each build.
 */
import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const repoRoot = resolve(__dirname, '..')
const entry = resolve(repoRoot, 'api/_bff-entry.ts')
const outfile = resolve(repoRoot, 'api/_bff-bundle.mjs')

// Tiny entry file that re-exports the two attach functions. Written to disk
// just-in-time so we don't ship a stray entrypoint.
const entrySource = `
export { attachDashboardBff } from '../server/dashboard-bff'
export { attachAgentFarmBff } from '../server/agent-farm-bff'
`
mkdirSync(dirname(entry), { recursive: true })
writeFileSync(entry, entrySource, 'utf8')

const result = await build({
  entryPoints: [entry],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  outfile,
  // Node built-ins stay external; everything else gets inlined.
  external: ['node:*'],
  // Source maps inline so Vercel runtime stacktraces still point at our code.
  sourcemap: 'inline',
  // Preserve `import.meta.url` semantics for any consumers that use it.
  banner: { js: '// Generated by scripts/bundle-bff.mjs — do not edit by hand.' },
  logLevel: 'info',
})

if (result.errors.length) {
  console.error('BFF bundle errors:', result.errors)
  process.exit(1)
}
if (result.warnings.length) {
  console.warn('BFF bundle warnings:', result.warnings)
}
console.log(`bundle-bff: wrote ${outfile}`)
